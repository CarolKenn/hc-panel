// GetSummary 导出前的数据概览
func (a *DataExport) GetSummary(c *gin.Context) {
	userInfo, _ := base.GetCurrentUserInfo(c)

	summary := panelApiStructs.DataExportSummary{
		Username:   userInfo.Username,
		AppVersion: cmn.GetSysVersionInfo().Version,
	}

	if err := global.Db.Model(&models.ItemIconGroup{}).Where("user_id=?", userInfo.ID).Count(&summary.GroupCount).Error; err != nil {
		apiReturn.ErrorDatabase(c, err.Error())
		return
	}

	if err := global.Db.Model(&models.ItemIcon{}).Where("user_id=?", userInfo.ID).Count(&summary.IconCount).Error; err != nil {
		apiReturn.ErrorDatabase(c, err.Error())
		return
	}

	files := []models.File{}
	if err := global.Db.Find(&files, "user_id=?", userInfo.ID).Error; err != nil {
		apiReturn.ErrorDatabase(c, err.Error())
		return
	}
	summary.FileCount = int64(len(files))
	for _, file := range files {
		if info, err := os.Stat(file.Src); err == nil && !info.IsDir() {
			summary.FileSize += info.Size()
		}
	}

	var configCount int64
	if err := global.Db.Model(&models.UserConfig{}).Where("user_id=?", userInfo.ID).Count(&configCount).Error; err != nil {
		apiReturn.ErrorDatabase(c, err.Error())
		return
	}
	summary.HasStyle = configCount > 0

	apiReturn.SuccessData(c, summary)
}

// Export 导出当前账号的全部数据，返回 ZIP 压缩包
func (a *DataExport) Export(c *gin.Context) {
	userInfo, _ := base.GetCurrentUserInfo(c)

	req := panelApiStructs.DataExportRequest{}
	// 请求体允许为空，解析失败时使用默认值（全部导出）
	_ = c.ShouldBindBodyWith(&req, binding.JSON)

	includeIcons := boolOrDefault(req.IncludeIcons, true)
	includeStyle := boolOrDefault(req.IncludeStyle, true)
	includeFiles := boolOrDefault(req.IncludeFiles, true)

	manifest := exportManifest{
		AppName:       exportAppName,
		FormatVersion: exportFormatVersion,
		AppVersion:    cmn.GetSysVersionInfo().Version,
		ExportTime:    time.Now().Format("2006-01-02 15:04:05"),
		User: exportUserInfo{
			ID:         userInfo.ID,
			Username:   userInfo.Username,
			Name:       userInfo.Name,
			HeadImage:  userInfo.HeadImage,
			Mail:       userInfo.Mail,
			Role:       userInfo.Role,
			CreateTime: userInfo.CreatedAt,
		},
	}

	if includeIcons {
		groups, groupCount, iconCount, err := queryExportIcons(userInfo.ID)
		if err != nil {
			apiReturn.ErrorDatabase(c, err.Error())
			return
		}
		manifest.IconGroups = groups
		manifest.Stats.GroupCount = groupCount
		manifest.Stats.IconCount = iconCount
	}

	if includeStyle {
		panelConfig, searchEngine, exist, err := queryExportUserConfig(userInfo.ID)
		if err != nil {
			apiReturn.ErrorDatabase(c, err.Error())
			return
		}
		if exist {
			manifest.Panel = panelConfig
			manifest.SearchEngine = searchEngine
		}
	}

	entries := []exportFileEntry{}
	if includeFiles {
		files := []models.File{}
		if err := global.Db.Order("created_at").Find(&files, "user_id=?", userInfo.ID).Error; err != nil {
			apiReturn.ErrorDatabase(c, err.Error())
			return
		}
		entries = buildExportFileEntries(files)
	}

	manifest.Files = entries
	for _, entry := range entries {
		manifest.Stats.FileCount++
		manifest.Stats.FileSize += entry.Size
	}

	zipPath, err := buildExportZip(&manifest, entries)
	if err != nil {
		apiReturn.Error(c, "export failed: "+err.Error())
		return
	}
	defer os.Remove(zipPath)

	fileName := fmt.Sprintf("SunPanel-Backup-%s-%s.zip", safeExportFileName(userInfo.Username), time.Now().Format("20060102-150405"))
	c.FileAttachment(zipPath, fileName)
}

// 查询图标分组与图标
func queryExportIcons(userId uint) (groups []exportItemIconGroup, groupCount, iconCount int, err error) {
	groupModels := []models.ItemIconGroup{}
	if err = global.Db.Order("sort, created_at").Find(&groupModels, "user_id=?", userId).Error; err != nil {
		return nil, 0, 0, err
	}

	iconModels := []models.ItemIcon{}
	if err = global.Db.Order("sort, created_at").Find(&iconModels, "user_id=?", userId).Error; err != nil {
		return nil, 0, 0, err
	}

	iconsByGroup := map[int][]exportItemIcon{}
	for _, icon := range iconModels {
		iconInfo := datatype.ItemIconIconInfo{}
		if icon.IconJson != "" {
			_ = json.Unmarshal([]byte(icon.IconJson), &iconInfo)
		}

		iconsByGroup[icon.ItemIconGroupId] = append(iconsByGroup[icon.ItemIconGroupId], exportItemIcon{
			ID:          icon.ID,
			Title:       icon.Title,
			Url:         icon.Url,
			LanUrl:      icon.LanUrl,
			Description: icon.Description,
			OpenMethod:  icon.OpenMethod,
			Sort:        icon.Sort,
			Icon:        iconInfo,
		})
	}

	groups = make([]exportItemIconGroup, 0, len(groupModels))
	for _, group := range groupModels {
		children := iconsByGroup[int(group.ID)]
		if children == nil {
			children = []exportItemIcon{}
		}
		delete(iconsByGroup, int(group.ID))

		groups = append(groups, exportItemIconGroup{
			ID:          group.ID,
			Title:       group.Title,
			Icon:        group.Icon,
			Description: group.Description,
			Sort:        group.Sort,
			Children:    children,
		})
	}

	// 兜底：分组已被删除但图标仍存在时，放入“未分组”，避免导出丢数据
	if len(iconsByGroup) > 0 {
		orphans := []exportItemIcon{}
		for _, children := range iconsByGroup {
			orphans = append(orphans, children...)
		}
		groups = append(groups, exportItemIconGroup{
			Title:    "Ungrouped",
			Children: orphans,
		})
	}

	return groups, len(groupModels), len(iconModels), nil
}

// 查询用户的面板样式与搜索引擎配置
func queryExportUserConfig(userId uint) (panelConfig, searchEngine map[string]interface{}, exist bool, err error) {
	cfg := models.UserConfig{}
	if err = global.Db.First(&cfg, "user_id=?", userId).Error; err != nil {
		if err == gorm.ErrRecordNotFound {
			return nil, nil, false, nil
		}
		return nil, nil, false, err
	}

	panelConfig = map[string]interface{}{}
	if cfg.PanelJson != "" {
		_ = json.Unmarshal([]byte(cfg.PanelJson), &panelConfig)
	}

	searchEngine = map[string]interface{}{}
	if cfg.SearchEngineJson != "" {
		_ = json.Unmarshal([]byte(cfg.SearchEngineJson), &searchEngine)
	}

	return panelConfig, searchEngine, true, nil
}

// 生成文件记录（包含归档路径与大小）
func buildExportFileEntries(files []models.File) []exportFileEntry {
	entries := make([]exportFileEntry, 0, len(files))
	usedArchivePath := map[string]int{}

	for _, file := range files {
		entry := exportFileEntry{
			ID:       file.ID,
			FileName: file.FileName,
			Ext:      file.Ext,
			Src:      file.Src,
			DiskPath: file.Src,
		}

		info, statErr := os.Stat(file.Src)
		if statErr != nil || info.IsDir() {
			entry.Missing = true
			entries = append(entries, entry)
			continue
		}

		entry.Size = info.Size()
		archivePath := buildArchivePath(file.Src)
		if archivePath == "" {
			entry.Missing = true
			entries = append(entries, entry)
			continue
		}

		// 同名文件自动追加序号，避免压缩包内覆盖
		if used, ok := usedArchivePath[archivePath]; ok {
			usedArchivePath[archivePath] = used + 1
			ext := path.Ext(archivePath)
			archivePath = fmt.Sprintf("%s_%d%s", strings.TrimSuffix(archivePath, ext), used+1, ext)
		} else {
			usedArchivePath[archivePath] = 1
		}

		entry.ArchivePath = archivePath
		entries = append(entries, entry)
	}

	return entries
}

// 生成压缩包内部的文件路径，保持原有目录结构
func buildArchivePath(src string) string {
	p := strings.ReplaceAll(src, "\\", "/")
	if p == "" {
		return ""
	}

	if filepath.IsAbs(p) {
		sourcePath := strings.TrimSuffix(strings.ReplaceAll(global.Config.GetValueString("base", "source_path"), "\\", "/"), "/")
		if sourcePath != "" && strings.HasPrefix(p, sourcePath+"/") {
			p = strings.TrimPrefix(p, sourcePath+"/")
		} else {
			p = path.Base(p)
		}
	} else {
		p = strings.TrimPrefix(p, "./")
		p = strings.TrimLeft(p, "/")
	}

	p = path.Clean(p)
	if p == "." || p == "" || strings.HasPrefix(p, "../") || p == ".." {
		return ""
	}

	return "files/" + p
}

// 构建导出压缩包，返回临时文件路径
func buildExportZip(manifest *exportManifest, entries []exportFileEntry) (zipPath string, err error) {
	tempDir := global.Config.GetValueString("base", "source_temp_path")
	if tempDir == "" {
		tempDir = "./runtime/temp"
	}

	if err = os.MkdirAll(tempDir, os.ModePerm); err != nil {
		return "", err
	}

	zipFile, err := os.CreateTemp(tempDir, "sun-panel-export-*.zip")
	if err != nil {
		return "", err
	}
	zipPath = zipFile.Name()

	completed := false
	defer func() {
		_ = zipFile.Close()
		if !completed {
			_ = os.Remove(zipPath)
		}
	}()

	zipWriter := zip.NewWriter(zipFile)

	jsonBytes, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return "", err
	}
	if err = writeZipBytes(zipWriter, "data.json", jsonBytes); err != nil {
		return "", err
	}
	if err = writeZipBytes(zipWriter, "README.txt", []byte(exportReadme)); err != nil {
		return "", err
	}

	for _, entry := range entries {
		if entry.Missing || entry.ArchivePath == "" {
			continue
		}
		if err = writeZipFile(zipWriter, entry.DiskPath, entry.ArchivePath); err != nil {
			return "", err
		}
	}

	if err = zipWriter.Close(); err != nil {
		return "", err
	}
	if err = zipFile.Close(); err != nil {
		return "", err
	}

	completed = true
	return zipPath, nil
}

func writeZipBytes(zipWriter *zip.Writer, name string, data []byte) error {
	writer, err := zipWriter.Create(name)
	if err != nil {
		return err
	}
	_, err = writer.Write(data)
	return err
}

func writeZipFile(zipWriter *zip.Writer, diskPath, archivePath string) error {
	src, err := os.Open(diskPath)
	if err != nil {
		return err
	}
	defer src.Close()

	info, err := src.Stat()
	if err != nil {
		return err
	}

	header, err := zip.FileInfoHeader(info)
	if err != nil {
		return err
	}
	header.Name = archivePath
	header.Method = zip.Deflate

	writer, err := zipWriter.CreateHeader(header)
	if err != nil {
		return err
	}

	_, err = io.Copy(writer, src)
	return err
}

func boolOrDefault(value *bool, defaultValue bool) bool {
	if value == nil {
		return defaultValue
	}
	return *value
}

// 仅保留字母与数字，避免下载文件名包含非法字符
func safeExportFileName(name string) string {
	var builder strings.Builder
	for _, r := range strings.TrimSpace(name) {
		if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') || r == '-' || r == '_' {
			builder.WriteRune(r)
		}
	}
	if builder.Len() == 0 {
		return "user"
	}
	return builder.String()
}
